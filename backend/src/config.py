"""Central settings.

Every path and secret can be overridden with an environment variable (or a
backend/.env file), so nothing machine-specific is hard-coded.
"""
import os
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]

try:
    from dotenv import load_dotenv

    load_dotenv(BACKEND_DIR / ".env")
except ImportError:  # python-dotenv is optional
    pass

# backend/ sits directly inside the TRACE repo, so its parent is the repo root.
REPO_ROOT = Path(os.getenv("TRACE_REPO_ROOT", BACKEND_DIR.parent))


def _path(env_name: str, default: Path) -> Path:
    return Path(os.getenv(env_name, str(default)))


# --- recommendation engine inputs (generated by teammates' pipelines) ---
ENGINE_SRC_DIR = _path("TRACE_ENGINE_SRC_DIR", REPO_ROOT / "graph-optimizer" / "src")
GRAPH_FILE = _path(
    "TRACE_GRAPH_FILE", REPO_ROOT / "multigraph-builder" / "output" / "unified_graph.json"
)
WEIGHTS_FILE = _path(
    "TRACE_WEIGHTS_FILE", REPO_ROOT / "graph-optimizer" / "output" / "best_weights.json"
)
FUNCTION_RANGES_FILE = _path(
    "TRACE_FUNCTION_RANGES_FILE", REPO_ROOT / "ast-parser" / "output" / "function_ranges.json"
)

# --- mock mode: serve backend/mock_data instead of the real engine ---
MOCK_DATA_FILE = BACKEND_DIR / "mock_data" / "mock_recommendations.json"
USE_MOCK = os.getenv("TRACE_USE_MOCK", "0") == "1"

# --- LLM (Gemini) ---
GEMINI_API_KEY = os.getenv("GEMINI_API_KEY", "")
# Model names get retired often; keep this configurable instead of hard-coded.
GEMINI_MODEL = os.getenv("GEMINI_MODEL", "gemini-flash-latest")
LLM_TIMEOUT_MS = int(os.getenv("LLM_TIMEOUT_MS", "30000"))
LLM_PER_FUNCTION_COOLDOWN_S = float(os.getenv("LLM_PER_FUNCTION_COOLDOWN_S", "10"))
LLM_MAX_CALLS_PER_MINUTE = int(os.getenv("LLM_MAX_CALLS_PER_MINUTE", "8"))
